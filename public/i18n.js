window.esc = function (s) {
  return String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
};
// Survey value as shown on screen: "1,176,583 people", "29.1%", "$2.92B", "$839B", "$395,000/year" —
// or the share of answers for opinion surveys. Units starting with "$" are money: the sign goes in front,
// the rest of the unit ("B", "/year") after the number, and amounts of a million or more are compacted.
window.fmtVal = function (a, g) {
  if (!g || !g.unit) return a.pct + '%';
  if (g.unit === 'rank') return '';   // ranking-only lists: the #position says it all
  const n = Number(a.count);
  if (!isFinite(n)) return '';
  const loc = LANG === 'en' ? 'en-US' : 'es-PE';
  if (g.unit[0] === '$') {
    const suffix = g.unit.slice(1);
    const s = n >= 1e6 && !suffix ? n.toLocaleString(loc, { notation: 'compact', maximumSignificantDigits: 3 })
      : n.toLocaleString(loc, { maximumFractionDigits: n < 10 ? 1 : 0 });
    return '$' + s + suffix;
  }
  const s = n > 0 && n < 0.01 ? n.toLocaleString(loc, { maximumSignificantDigits: 2 }) : n.toLocaleString(loc, { maximumFractionDigits: n < 10 ? 2 : n < 1000 ? 1 : 0 });
  return g.unit === '%' ? s + '%' : s + ' ' + g.unit;
};
